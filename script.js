function escapeHTML(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

function getTranslation(pack, key) {
  if (pack[key]) return pack[key];

  const aliasKey = legacyAliases[key];
  if (aliasKey && pack[aliasKey]) return pack[aliasKey];

  return "";
}

function setLanguage(lang) {
  const selectedLanguage = translations[lang] ? lang : "ko";
  const selected = translations[selectedLanguage];

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");
    const value = getTranslation(selected, key);

    if (!value) return;

    element.innerHTML = escapeHTML(value).replace(/\n/g, "<br />");
  });

  const htmlLangMap = {
    ko: "ko",
    en: "en",
    zh: "zh-CN",
    ja: "ja"
  };

  document.documentElement.lang = htmlLangMap[selectedLanguage] || selectedLanguage;

  if (pageMeta[selectedLanguage]) {
    document.title = pageMeta[selectedLanguage].title;

    const metaDescription = document.querySelector('meta[name="description"]');
    if (metaDescription) {
      metaDescription.setAttribute("content", pageMeta[selectedLanguage].description);
    }
  }

  try {
    localStorage.setItem("younghanLanguage", selectedLanguage);
  } catch (error) {
    console.warn("Language preference could not be saved.", error);
  }

  updateLanguageButtons(selectedLanguage);
}

function updateLanguageButtons(lang) {
  const buttons = document.querySelectorAll(".language button");

  buttons.forEach((button) => {
    const onclickValue = button.getAttribute("onclick") || "";
    const isActive =
      onclickValue.includes(`'${lang}'`) || onclickValue.includes(`"${lang}"`);

    button.classList.toggle("active", isActive);
  });
}

function initFadeAnimation() {
  const fadeElements = document.querySelectorAll(".fade");

  if (!fadeElements.length) return;

  if (!("IntersectionObserver" in window)) {
    fadeElements.forEach((element) => {
      element.classList.add("show");
    });
    return;
  }

  const observer = new IntersectionObserver(
    (entries, observerInstance) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("show");
          observerInstance.unobserve(entry.target);
        }
      });
    },
    {
      threshold: 0.12,
      rootMargin: "0px 0px -50px 0px"
    }
  );

  fadeElements.forEach((element) => {
    observer.observe(element);
  });
}

function initSmoothScroll() {
  const links = document.querySelectorAll('a[href^="#"]');

  links.forEach((link) => {
    link.addEventListener("click", (event) => {
      const href = link.getAttribute("href");

      if (!href || href === "#") return;

      let target = null;

      try {
        target = document.querySelector(href);
      } catch (error) {
        target = null;
      }

      if (!target) return;

      event.preventDefault();

      const header = document.querySelector(".header");
      const headerHeight = header ? header.offsetHeight : 0;
      const targetTop =
        target.getBoundingClientRect().top +
        window.pageYOffset -
        headerHeight -
        18;

      window.scrollTo({
        top: targetTop,
        behavior: "smooth"
      });

      closeMobileMenu();
    });
  });
}

function initHeaderScrollEffect() {
  const header = document.querySelector(".header");

  if (!header) return;

  const handleScroll = () => {
    header.classList.toggle("scrolled", window.scrollY > 10);
  };

  handleScroll();

  window.addEventListener("scroll", handleScroll, {
    passive: true
  });
}

function initActiveNavByScroll() {
  const navLinks = Array.from(document.querySelectorAll('.nav a[href^="#"]'));

  if (!navLinks.length || !("IntersectionObserver" in window)) return;

  const sections = navLinks
    .map((link) => {
      const href = link.getAttribute("href");
      let section = null;

      try {
        section = document.querySelector(href);
      } catch (error) {
        section = null;
      }

      return section ? { link, section } : null;
    })
    .filter(Boolean);

  if (!sections.length) return;

  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;

        const activeItem = sections.find((item) => item.section === entry.target);

        if (!activeItem) return;

        navLinks.forEach((link) => link.classList.remove("active"));
        activeItem.link.classList.add("active");
      });
    },
    {
      threshold: 0.24,
      rootMargin: "-18% 0px -58% 0px"
    }
  );

  sections.forEach((item) => observer.observe(item.section));
}

function initMobileMenu() {
  const menuToggle = document.querySelector(".menu-toggle");
  const nav = document.querySelector(".nav");

  if (!menuToggle || !nav) return;

  menuToggle.addEventListener("click", () => {
    const isOpen = nav.classList.toggle("open");

    menuToggle.classList.toggle("active", isOpen);
    menuToggle.setAttribute("aria-expanded", String(isOpen));
  });
}

function closeMobileMenu() {
  const menuToggle = document.querySelector(".menu-toggle");
  const nav = document.querySelector(".nav");

  if (!menuToggle || !nav) return;

  nav.classList.remove("open");
  menuToggle.classList.remove("active");
  menuToggle.setAttribute("aria-expanded", "false");
}

function getSavedLanguage() {
  try {
    return localStorage.getItem("younghanLanguage");
  } catch (error) {
    return null;
  }
}

function initPage() {
  const savedLanguage = getSavedLanguage();

  if (savedLanguage && translations[savedLanguage]) {
    setLanguage(savedLanguage);
  } else {
    setLanguage("ko");
  }

  initFadeAnimation();
  initSmoothScroll();
  initHeaderScrollEffect();
  initActiveNavByScroll();
  initMobileMenu();
}

window.setLanguage = setLanguage;

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initPage);
} else {
  initPage();
}
